/**
 * Returns a high-res image URL for raw material or grocery item based on name or category.
 */
export function getGroceryImage(name = "", category = "", customImage = "") {
  const str = `${name} ${category}`.toLowerCase().trim();

  if (customImage && typeof customImage === "string" && customImage.trim().startsWith("http")) {
    // If it was assigned the old generic vegetable shelf fallback (photo-1542838132-92c53300491e),
    // and this is a specific item like coffee, salt, milk, chicken, bread, etc., override it with the exact photo!
    if (customImage.includes("542838132-92c53300491e") && !str.includes("vegetable") && !str.includes("grocery") && !str.includes("produce")) {
      // Fall through to exact item resolver below!
    } else {
      return customImage.trim();
    }
  }

  // Chakra Gold & Branded Tea
  if (str.includes("chakra") || str.includes("tata tea")) {
    return GROCERY_IMAGE_PRESETS.chakra_gold;
  }

  // Tata Salt & Branded Salt
  if (str.includes("tata salt") || str.includes("tata") && str.includes("salt")) {
    return GROCERY_IMAGE_PRESETS.tata_salt;
  }

  // Bru Coffee
  if (str.includes("bru")) {
    return GROCERY_IMAGE_PRESETS.bru;
  }

  // Coffee & Coffee Powder (handles 'coffe', 'coffee', 'kaapi', 'bru', 'nescafe', etc.)
  if (str.includes("coffe") || str.includes("kaapi") || str.includes("espresso") || str.includes("nescafe") || str.includes("bru") || str.includes("cappuccino") || str.includes("latte")) {
    return GROCERY_IMAGE_PRESETS.coffee;
  }

  // Salt & Tata Salt
  if (str.includes("salt") || str.includes("uppu") || str.includes("tata salt") || str.includes("rock salt")) {
    return GROCERY_IMAGE_PRESETS.salt;
  }

  // Chicken & Poultry
  if (str.includes("chinthu") || str.includes("chicken") || str.includes("koli") || str.includes("broiler") || str.includes("patty") || str.includes("nattu")) {
    return GROCERY_IMAGE_PRESETS.chicken;
  }

  // Milk & Dairy
  if (str.includes("milk") || str.includes("paal") || str.includes("dairy") || str.includes("amul") || str.includes("arokya") || str.includes("curd") || str.includes("thayir")) {
    return GROCERY_IMAGE_PRESETS.milk;
  }

  // Tea
  if (str.includes("tea") || str.includes("chai") || str.includes("leaves") || str.includes("taj mahal") || str.includes("red label") || str.includes("3 roses")) {
    return GROCERY_IMAGE_PRESETS.tea;
  }

  // Sugar
  if (str.includes("sugar") || str.includes("sakkarai") || str.includes("vellam") || str.includes("jaggery")) {
    return GROCERY_IMAGE_PRESETS.sugar;
  }

  // Bread & Bakery
  if (str.includes("bread") || str.includes("loaf") || str.includes("toast") || str.includes("sandwich")) {
    return GROCERY_IMAGE_PRESETS.bread;
  }
  if (str.includes("bun") || str.includes("pav") || str.includes("bakery") || str.includes("roll")) {
    return GROCERY_IMAGE_PRESETS.bun;
  }

  // Cooking Oil & Ghee
  if (str.includes("oil") || str.includes("ennai") || str.includes("sunflower") || str.includes("olive") || str.includes("gingelly") || str.includes("coconut oil")) {
    return GROCERY_IMAGE_PRESETS.oil;
  }
  if (str.includes("ghee") || str.includes("nei")) {
    return GROCERY_IMAGE_PRESETS.ghee;
  }

  // Rice & Grains
  if (str.includes("rice") || str.includes("arisi") || str.includes("basmati") || str.includes("biryani") || str.includes("ponni")) {
    return GROCERY_IMAGE_PRESETS.rice;
  }
  if (str.includes("flour") || str.includes("atta") || str.includes("maida") || str.includes("wheat") || str.includes("rava") || str.includes("sooji")) {
    return GROCERY_IMAGE_PRESETS.flour;
  }

  // Meat & Seafood
  if (str.includes("mutton") || str.includes("goat") || str.includes("lamb")) {
    return GROCERY_IMAGE_PRESETS.mutton;
  }
  if (str.includes("fish") || str.includes("seafood") || str.includes("prawn") || str.includes("meen")) {
    return GROCERY_IMAGE_PRESETS.fish;
  }
  if (str.includes("meat") || str.includes("beef") || str.includes("pork")) {
    return GROCERY_IMAGE_PRESETS.meat;
  }

  // Dairy Products
  if (str.includes("cheese")) {
    return GROCERY_IMAGE_PRESETS.cheese;
  }
  if (str.includes("paneer")) {
    return GROCERY_IMAGE_PRESETS.paneer;
  }
  if (str.includes("butter") || str.includes("vennai")) {
    return GROCERY_IMAGE_PRESETS.butter;
  }
  if (str.includes("egg") || str.includes("muttai") || str.includes("poultry")) {
    return GROCERY_IMAGE_PRESETS.egg;
  }

  // Produce & Vegetables
  if (str.includes("onion") || str.includes("vengayam")) {
    return GROCERY_IMAGE_PRESETS.onion;
  }
  if (str.includes("tomato") || str.includes("thakkali")) {
    return GROCERY_IMAGE_PRESETS.tomato;
  }
  if (str.includes("potato") || str.includes("urulai") || str.includes("aloo")) {
    return GROCERY_IMAGE_PRESETS.potato;
  }
  if (str.includes("chilli") || str.includes("chili") || str.includes("milagai") || str.includes("mirchi")) {
    return GROCERY_IMAGE_PRESETS.chilli;
  }
  if (str.includes("garlic") || str.includes("poondhu")) {
    return GROCERY_IMAGE_PRESETS.garlic;
  }
  if (str.includes("ginger") || str.includes("inji")) {
    return GROCERY_IMAGE_PRESETS.ginger;
  }
  if (str.includes("mint") || str.includes("pudhina") || str.includes("coriander") || str.includes("koththamalli")) {
    return GROCERY_IMAGE_PRESETS.mint;
  }
  if (str.includes("lemon") || str.includes("elumichai") || str.includes("lime")) {
    return GROCERY_IMAGE_PRESETS.lemon;
  }

  // Sauces & Condiments
  if (str.includes("sauce") || str.includes("ketchup") || str.includes("mayo")) {
    return GROCERY_IMAGE_PRESETS.sauce;
  }
  if (str.includes("spice") || str.includes("masala") || str.includes("pepper") || str.includes("turmeric") || str.includes("manjal")) {
    return GROCERY_IMAGE_PRESETS.spices;
  }

  // Packaging
  if (str.includes("cup") || str.includes("glass")) {
    return GROCERY_IMAGE_PRESETS.cups;
  }
  if (str.includes("box") || str.includes("packaging") || str.includes("parcel") || str.includes("container") || str.includes("bag")) {
    return GROCERY_IMAGE_PRESETS.packaging;
  }
  if (str.includes("vegetable") || str.includes("produce") || str.includes("salad")) {
    return GROCERY_IMAGE_PRESETS.vegetables;
  }

  return GROCERY_IMAGE_PRESETS.grocery;
}
